package main

import (
	"encoding/json"
	"fmt"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"
	"unicode/utf8"
)

type countryInRegion struct {
	Name struct {
		Common string `json:"common"`
	} `json:"name"`
	Cca3 string `json:"cca3"`
}

type countryDetail struct {
	Name struct {
		Common string `json:"common"`
	} `json:"name"`
	Capital    []string `json:"capital"`
	Cca3       string   `json:"cca3"`
	Region     string   `json:"region"`
	Population *int64   `json:"population"`
}

const apiBase = "https://api-opgaver.mercantec.tech"

var regions = []string{"Europe", "Asia", "Africa"}

func main() {
	client := &http.Client{
		Timeout: 15 * time.Second,
	}

	regionResults := make(map[string][]string)

	for _, region := range regions {
		fmt.Printf("Fetching region: %s...\n", region)
		endpoint := fmt.Sprintf("%s/api/Countries/region/%s", apiBase, region)

		resp, err := client.Get(endpoint)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error getting region %s: %v\n", region, err)
			os.Exit(1)
		}

		if resp.StatusCode != http.StatusOK {
			resp.Body.Close()
			fmt.Fprintf(os.Stderr, "region %s returned status %d\n", region, resp.StatusCode)
			os.Exit(1)
		}

		var list []countryInRegion
		err = json.NewDecoder(resp.Body).Decode(&list)
		resp.Body.Close()
		if err != nil {
			fmt.Fprintf(os.Stderr, "error parsing region %s json: %v\n", region, err)
			os.Exit(1)
		}

		skipped := 0
		var candidates []string
		for _, c := range list {
			common := strings.TrimSpace(c.Name.Common)
			cca3 := strings.TrimSpace(c.Cca3)
			if common == "" || cca3 == "" {
				skipped++
				continue
			}
			candidates = append(candidates, common)
		}

		var validNames []string
		for _, rawName := range candidates {
			detailURL := fmt.Sprintf("%s/api/Countries/name/%s", apiBase, url.PathEscape(rawName))
			detailResp, err := client.Get(detailURL)
			if err != nil {
				fmt.Printf("  [SKIP] %s: network error: %v\n", rawName, err)
				skipped++
				continue
			}

			if detailResp.StatusCode != http.StatusOK {
				detailResp.Body.Close()
				fmt.Printf("  [SKIP] %s: HTTP %d\n", rawName, detailResp.StatusCode)
				skipped++
				continue
			}

			var detail countryDetail
			err = json.NewDecoder(detailResp.Body).Decode(&detail)
			detailResp.Body.Close()
			if err != nil {
				fmt.Printf("  [SKIP] %s: json parse error: %v\n", rawName, err)
				skipped++
				continue
			}

			if detail.Name.Common == "" {
				fmt.Printf("  [SKIP] %s: name.common missing\n", rawName)
				skipped++
				continue
			}
			if len(detail.Capital) == 0 || strings.TrimSpace(detail.Capital[0]) == "" {
				fmt.Printf("  [SKIP] %s: capital[0] missing or empty\n", rawName)
				skipped++
				continue
			}
			if len(detail.Cca3) != 3 {
				fmt.Printf("  [SKIP] %s: cca3 invalid (%q)\n", rawName, detail.Cca3)
				skipped++
				continue
			}
			if detail.Region == "" {
				fmt.Printf("  [SKIP] %s: region missing\n", rawName)
				skipped++
				continue
			}
			if detail.Population == nil || *detail.Population < 0 {
				fmt.Printf("  [SKIP] %s: population missing or negative\n", rawName)
				skipped++
				continue
			}

			repairedName := repairBrokenUTF8(rawName)
			validNames = append(validNames, repairedName)
		}

		fmt.Printf("Region %s: total raw=%d, skipped=%d, valid=%d\n", region, len(list), skipped, len(validNames))
		regionResults[region] = validNames
	}

	headerPath := filepath.Join("arduino", "countries.h")
	err := writeHeaderFile(headerPath, regionResults)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error writing countries.h: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Successfully wrote %s\n", headerPath)
}

func repairBrokenUTF8(s string) string {
	if s == "" {
		return s
	}

	buf := make([]byte, 0, len(s))
	for _, r := range s {
		if r > 0xFF {
			return s
		}
		buf = append(buf, byte(r))
	}

	if !utf8.Valid(buf) {
		return s
	}

	return string(buf)
}

func writeHeaderFile(path string, data map[string][]string) error {
	var sb strings.Builder
	sb.WriteString("// Generated by tools/gencountries. Do not edit manually.\n\n")
	sb.WriteString("#ifndef COUNTRIES_H\n")
	sb.WriteString("#define COUNTRIES_H\n\n")

	writeRegionArray(&sb, "europe", data["Europe"])
	writeRegionArray(&sb, "asia", data["Asia"])
	writeRegionArray(&sb, "africa", data["Africa"])

	sb.WriteString("#endif\n")

	return os.WriteFile(path, []byte(sb.String()), 0644)
}

func writeRegionArray(sb *strings.Builder, prefix string, names []string) {
	fmt.Fprintf(sb, "const char* const %sCountries[] = {\n", prefix)
	for _, n := range names {
		escaped := strings.ReplaceAll(n, `\`, `\\`)
		escaped = strings.ReplaceAll(escaped, `"`, `\"`)
		fmt.Fprintf(sb, "    \"%s\",\n", escaped)
	}
	sb.WriteString("};\n")
	fmt.Fprintf(sb, "const int %sCount = sizeof(%sCountries) / sizeof(%sCountries[0]);\n\n", prefix, prefix, prefix)
}
